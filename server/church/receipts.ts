import { and, eq, lt } from "drizzle-orm";
import { err, ok, type Result } from "@/lib/result";
import type { Database } from "@/server/db/client";
import { commandReceipts } from "@/server/db/schema";

/**
 * Idempotent commands: the same request, arriving twice, is done once.
 *
 * The browser gives each intent a request id and reuses it for every retry.
 * Before a command runs, the server claims that id for the church; a second
 * arrival finds the claim and is answered from it instead of running again.
 * See `commandReceipts` in the schema for why this exists.
 */

/** How long a receipt is kept. A retry arrives within seconds, not days. */
const RETENTION_MS = 24 * 60 * 60 * 1000;

/** A request id is ours to accept: generated by the browser, so checked here. */
export const REQUEST_ID_PATTERN = /^[A-Za-z0-9_-]{8,64}$/;

/** Refusal code: the first copy of this request is still being saved. */
export const IN_PROGRESS = "in_progress";

export interface ReceiptKey {
  churchId: string;
  requestId: string;
  userId: string;
  command: string;
}

export interface StoredResponse {
  notices: string[];
  data: Record<string, unknown>;
}

export type Claim =
  /** Nobody has seen this request: run it, then `complete` or `release`. */
  | { kind: "claimed" }
  /** It already ran: answer with what it said the first time. */
  | { kind: "replay"; response: StoredResponse };

export async function claimReceipt(
  db: Database,
  key: ReceiptKey,
): Promise<Result<Claim>> {
  const inserted = await db
    .insert(commandReceipts)
    .values({ ...key, status: "pending" })
    .onConflictDoNothing()
    .returning({ requestId: commandReceipts.requestId });
  if (inserted.length) {
    await pruneReceipts(db, key.churchId);
    return ok({ kind: "claimed" });
  }

  const [existing] = await db
    .select()
    .from(commandReceipts)
    .where(
      and(
        eq(commandReceipts.churchId, key.churchId),
        eq(commandReceipts.requestId, key.requestId),
      ),
    );

  // Released between our insert and our read: the first attempt was refused,
  // so this one may simply try again.
  if (!existing) return claimReceipt(db, key);

  // An id is only a key for the request it was made for. Somebody else's id,
  // or the same id on a different command, is not a retry.
  if (existing.userId !== key.userId || existing.command !== key.command) {
    return err(
      "That request id has already been used for something else.",
      "invalid_input",
    );
  }

  if (existing.status === "done" && existing.response) {
    return ok({ kind: "replay", response: existing.response });
  }
  return err(
    "That change is still being saved. It will appear in a moment.",
    IN_PROGRESS,
  );
}

/** The command was saved: remember what it said, for any retry. */
export async function completeReceipt(
  db: Database,
  key: ReceiptKey,
  response: StoredResponse,
): Promise<void> {
  await db
    .update(commandReceipts)
    .set({ status: "done", response })
    .where(
      and(
        eq(commandReceipts.churchId, key.churchId),
        eq(commandReceipts.requestId, key.requestId),
      ),
    );
}

/** The command was refused or failed: nothing happened, so a retry may run it. */
export async function releaseReceipt(
  db: Database,
  key: ReceiptKey,
): Promise<void> {
  await db
    .delete(commandReceipts)
    .where(
      and(
        eq(commandReceipts.churchId, key.churchId),
        eq(commandReceipts.requestId, key.requestId),
      ),
    );
}

async function pruneReceipts(db: Database, churchId: string): Promise<void> {
  await db
    .delete(commandReceipts)
    .where(
      and(
        eq(commandReceipts.churchId, churchId),
        lt(commandReceipts.createdAt, new Date(Date.now() - RETENTION_MS)),
      ),
    );
}
